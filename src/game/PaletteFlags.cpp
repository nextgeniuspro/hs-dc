// A .tc stream carries either direct ARGB4444 pixels or 12-bit palette indices,
// and nothing in the file says which: the engine decides at the call site, by
// which of two loader wrappers it uses (0x100b572c passes 0 -> direct colour,
// 0x100b573c passes 1 -> indexed, palette at obj+0x48). Guessing from pixel
// values gets it wrong on dark textures whose indices happen to look like
// plausible colours -- fog, water2, smallprojectile, seagull_shadow and
// anim/img/black all fooled that heuristic, and the symptom is sprites that
// render blue-green with red always zero.
//
// So these are ground truth instead: the flag the running game passed, logged
// by the EKA2L1 probe in tools/eka2l1/ over several play sessions. 283 assets
// were observed; anything not listed falls back to the heuristic.
//
