std::optional<bool> RuntimePaletted(const std::string& gamePath) {
    // Canonical form: uppercase, forward slashes, "DATA/" prefix -- the same
    // normalisation the pak name hash uses.
    std::string key;
    key.reserve(gamePath.size() + 5);
    for (char c : gamePath)
        key.push_back(c == '\\' ? '/' : static_cast<char>(std::toupper(
            static_cast<unsigned char>(c))));
    if (key.rfind("DATA/", 0) != 0) key.insert(0, "DATA/");

    const auto* end = kFlags + sizeof(kFlags) / sizeof(kFlags[0]);
    const auto* it = std::lower_bound(
        kFlags, end, key, [](const Flag& f, const std::string& k) {
            return std::strcmp(f.Path, k.c_str()) < 0;
        });
    if (it == end || key != it->Path) return std::nullopt;
    return it->Indexed;
}

